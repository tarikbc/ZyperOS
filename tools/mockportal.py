#!/usr/bin/env python3
"""Write docs/design/mock/portal.js: the File Transfer page's own pieces for
a design lab that draws the page.

    python3 tools/mockportal.py [OUT]

A lab that draws the page (res/web) should draw it with the page's real
stylesheet and the shelf's real system icons, not with a copy that drifts.
This puts them in one script, window.ZYPER_PORTAL:

  css      res/web/app.css as it is
  marks    the lockups and Zyper (res/web/*.svg) as data: URIs
  icons    every res/system-icons/<KEY>-still.png as a data: URI
  systems  config/systems.cfg's shelves: name, folder, tag, the icon key the
           shelf uses for the tag (home.c's asset_for), accent color

tools/mockpage.py inlines it into a lab page like kit.js. Standard library
only; never edit portal.js by hand.
"""
import base64
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# home.c's asset_for: a tag whose art has another name
ASSET_FOR = {"SFC": "SNES", "MD": "GENESIS", "PRT": "PORTS", "FAV": "FAVORITES"}


def data_uri(path, mime):
    with open(path, "rb") as f:
        return "data:%s;base64,%s" % (mime, base64.b64encode(f.read()).decode("ascii"))


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "docs", "design", "mock", "portal.js")
    web = os.path.join(ROOT, "res", "web")
    with open(os.path.join(web, "app.css")) as f:
        css = f.read()
    marks = {}
    for name in ("mark", "mark-light", "zyper", "zyper-shut", "icon"):
        marks[name] = data_uri(os.path.join(web, name + ".svg"), "image/svg+xml")
    icons = {}
    folder = os.path.join(ROOT, "res", "system-icons")
    for name in sorted(os.listdir(folder)):
        if name.endswith("-still.png"):
            icons[name[: -len("-still.png")]] = data_uri(os.path.join(folder, name), "image/png")
    systems = []
    with open(os.path.join(ROOT, "config", "systems.cfg")) as f:
        for line in f:
            if not line.startswith("sys|"):
                continue
            field = [x.strip() for x in line.rstrip("\n").split("|")]
            if len(field) < 7:
                continue
            tag = field[4]
            systems.append({"name": field[1], "folder": field[2], "tag": tag,
                            "key": ASSET_FOR.get(tag, tag), "color": field[6]})
    data = {"css": css, "marks": marks, "icons": icons, "systems": systems}
    with open(out, "w") as f:
        f.write("/* Generated by tools/mockportal.py from res/web, res/system-icons and\n"
                " * config/systems.cfg: never edit it by hand. */\n")
        f.write("window.ZYPER_PORTAL = ")
        json.dump(data, f, separators=(",", ":"))
        f.write(";\n")


if __name__ == "__main__":
    main()
