#!/bin/sh
# Derives buildroot/board/qemu/linux.config from the kernel's allnoconfig and
# board/qemu/linux-qemu.fragment, as a minimal defconfig (savedefconfig), so
# the file says only what differs from the kernel's own defaults. Runs in the
# build container against an unpatched kernel tree of the version
# qemu_defconfig names:
#
#   sh /src/scripts/kernel-config-qemu.sh /work/output-qemu/build/linux-7.1.2
set -eu

TREE=$1
BOARD=/src/buildroot/board/qemu
cd "$TREE"

make ARCH=arm64 KCONFIG_ALLCONFIG="$BOARD/linux-qemu.fragment" allnoconfig >/dev/null

# What the fragment asked for and the kernel would not give, by name
grep -E "^(# )?CONFIG_" "$BOARD/linux-qemu.fragment" | sed -E 's/^# (CONFIG_[A-Za-z0-9_]+) is not set/\1=n/' |
while IFS== read -r symbol want; do
	got=$(grep -E "^$symbol=" .config | cut -d= -f2-)
	[ -n "$got" ] || got=n
	[ "$got" = "$want" ] || echo "note: $symbol is $got, not $want" >&2
done

make ARCH=arm64 savedefconfig >/dev/null
{
	echo "# Generated by scripts/kernel-config-qemu.sh from linux-qemu.fragment;"
	echo "# edit the fragment and run the script again, not this file."
	cat defconfig
} > "$BOARD/linux.config"
echo "linux.config: $(grep -c '=y$' .config) built in, $(grep -c '=m$' .config) modules"
